import type { AppDefinition, FieldDefinition, RouteDefinition, TypeDefinition, TypeRef } from "./ast.ts";

export interface GenerateOptions {
  handlersImport?: string;
  sourceImport?: string;
}

export function generate(app: AppDefinition, options: GenerateOptions = {}): string {
  const handlersImport = options.handlersImport ?? "./handlers.ts";
  const lines: string[] = [];
  lines.push("// Generated by buncompiler. Do not edit this file directly.");
  if (app.nest) {
    const classes = [...new Set([...app.nest.providers, ...app.nest.controllers].map((item) => item.name))];
    lines.push(`import { ${classes.join(", ")} } from ${JSON.stringify(app.nest.sourceImport)};`, "");
  } else {
    lines.push(`import { handlers } from ${JSON.stringify(handlersImport)};`, "");
  }
  lines.push("export interface RequestContext<P = undefined, Q = undefined, B = undefined> {");
  lines.push("  request: Request;", "  params: P;", "  query: Q;", "  body: B;", "}", "");

  for (const type of app.types) emitType(lines, type);
  emitPermissions(lines, app);
  if (app.nest) emitNestBootstrap(lines, app);
  else emitHandlerContract(lines, app);
  emitRuntimeHelpers(lines);
  emitPatterns(lines, app);
  for (const type of app.types) emitParser(lines, type);
  emitServer(lines, app);
  return lines.join("\n") + "\n";
}

function emitType(lines: string[], type: TypeDefinition): void {
  lines.push(`export interface ${type.name} {`);
  for (const field of type.fields) {
    lines.push(`  ${field.name}${field.optional ? "?" : ""}: ${tsType(field.type)};`);
  }
  lines.push("}", "");
}

function emitPermissions(lines: string[], app: AppDefinition): void {
  lines.push("export const Permission = {");
  for (const permission of app.permissions) lines.push(`  ${permission.name}: ${permission.value},`);
  lines.push("} as const;", "");
}

function emitHandlerContract(lines: string[], app: AppDefinition): void {
  const needsAuthorization = app.routes.some((route) => route.permission);
  lines.push("export interface GeneratedHandlers {");
  if (needsAuthorization) lines.push("  authorize(request: Request, permission: number): boolean | Promise<boolean>;");
  for (const route of app.routes) {
    const params = route.params ?? "undefined";
    const query = route.query ?? "undefined";
    const body = route.body ?? "undefined";
    lines.push(`  ${route.handler}(context: RequestContext<${params}, ${query}, ${body}>): unknown | Promise<unknown>;`);
  }
  lines.push("}");
  lines.push("const appHandlers: GeneratedHandlers = handlers;", "");
}

function emitNestBootstrap(lines: string[], app: AppDefinition): void {
  const nest = app.nest!;
  const variables = new Map([...nest.providers, ...nest.controllers].map((item) => [item.name, item.variable]));
  for (const provider of nest.providers) {
    const dependencies = provider.dependencies.map((name) => variables.get(name) ?? missingDependency(name, provider.name));
    lines.push(`const ${provider.variable} = new ${provider.name}(${dependencies.join(", ")});`);
  }
  for (const controller of nest.controllers) {
    const dependencies = controller.dependencies.map((name) => variables.get(name) ?? missingDependency(name, controller.name));
    lines.push(`const ${controller.variable} = new ${controller.name}(${dependencies.join(", ")});`);
  }
  lines.push("");
}

function missingDependency(name: string, owner: string): never {
  throw new Error(`Cannot generate ${owner}: dependency '${name}' has no generated instance`);
}

function emitRuntimeHelpers(lines: string[]): void {
  lines.push("type ParseResult<T> = { ok: true; value: T } | { ok: false; field: string; message: string };", "");
  lines.push("const jsonHeaders = { \"content-type\": \"application/json; charset=utf-8\" } as const;");
  lines.push("const textHeaders = { \"content-type\": \"text/plain; charset=utf-8\" } as const;");
  lines.push("function json(value: unknown, status = 200): Response {");
  lines.push("  return new Response(JSON.stringify(value), { status, headers: jsonHeaders });", "}");
  lines.push("function invalid(result: { field: string; message: string }): Response {");
  lines.push("  return json({ error: \"INVALID_INPUT\", field: result.field, message: result.message }, 400);", "}");
  lines.push("function isRecord(value: unknown): value is Record<string, unknown> {");
  lines.push("  return typeof value === \"object\" && value !== null && !Array.isArray(value);", "}");
  lines.push("async function bodyAsJson(request: Request): Promise<unknown> {");
  lines.push("  try { return await request.json(); } catch { return undefined; }", "}");
  lines.push("function toResponse(value: unknown, status: number): Response {");
  lines.push("  if (value instanceof Response) return value;");
  lines.push("  if (typeof value === \"string\") return new Response(value, { status, headers: textHeaders });");
  lines.push("  return json(value, status);", "}", "");
  lines.push("function exceptionResponse(error: unknown): Response {");
  lines.push("  if (typeof error === \"object\" && error !== null && \"status\" in error && typeof error.status === \"number\") {");
  lines.push("    return json({ error: error instanceof Error ? error.message : \"Request failed\" }, error.status);");
  lines.push("  }");
  lines.push("  console.error(error);");
  lines.push("  return json({ error: \"INTERNAL_SERVER_ERROR\" }, 500);", "}", "");
  lines.push("function executionContext(request: Request, controller: object, handler: Function): any {");
  lines.push("  return {");
  lines.push("    switchToHttp: () => ({ getRequest: () => request }),");
  lines.push("    getClass: () => controller.constructor,");
  lines.push("    getHandler: () => handler,");
  lines.push("  };", "}", "");
  lines.push("function decodePathSegment(value: string): string | undefined {");
  lines.push("  try { return decodeURIComponent(value); } catch { return undefined; }", "}", "");
}

function emitPatterns(lines: string[], app: AppDefinition): void {
  for (const type of app.types) {
    for (const field of type.fields) {
      const pattern = field.constraints.find((constraint) => constraint.name === "pattern");
      if (pattern) lines.push(`const pattern_${type.name}_${field.name} = new RegExp(${JSON.stringify(String(pattern.value))});`);
    }
  }
  if (lines.at(-1)?.startsWith("const pattern_")) lines.push("");
}

function emitParser(lines: string[], type: TypeDefinition): void {
  lines.push(`function parse${type.name}(input: unknown, source: \"json\" | \"text\" = \"json\"): ParseResult<${type.name}> {`);
  lines.push(`  if (!isRecord(input)) return { ok: false, field: \"${type.name}\", message: \"Expected an object\" };`);
  lines.push(`  const output = {} as ${type.name};`);
  for (const field of type.fields) emitFieldParser(lines, field, type.name);
  lines.push("  return { ok: true, value: output };", "}", "");
}

function emitFieldParser(lines: string[], field: FieldDefinition, owner: string): void {
  const raw = `raw_${field.name}`;
  const value = `value_${field.name}`;
  lines.push(`  const ${raw} = input[${JSON.stringify(field.name)}];`);
  if (field.optional) {
    lines.push(`  if (${raw} !== undefined) {`);
    emitValueParsing(lines, field, owner, raw, value, "    ");
    lines.push(`    output.${field.name} = ${value};`, "  }");
  } else {
    lines.push(`  if (${raw} === undefined) return { ok: false, field: ${JSON.stringify(field.name)}, message: \"Required field is missing\" };`);
    emitValueParsing(lines, field, owner, raw, value, "  ");
    lines.push(`  output.${field.name} = ${value};`);
  }
}

function emitValueParsing(lines: string[], field: FieldDefinition, owner: string, raw: string, value: string, indent: string): void {
  if (field.type.array) {
    lines.push(`${indent}if (!Array.isArray(${raw})) return { ok: false, field: ${JSON.stringify(field.name)}, message: \"Expected an array\" };`);
    lines.push(`${indent}const ${value}: ${tsType(field.type)} = [];`);
    lines.push(`${indent}for (let index = 0; index < ${raw}.length; index++) {`);
    emitScalarParsing(lines, { ...field, type: { ...field.type, array: false }, constraints: [] }, owner, `${raw}[index]`, "item", indent + "  ", `${field.name}[\${index}]`);
    lines.push(`${indent}  ${value}.push(item as never);`, `${indent}}`);
  } else {
    emitScalarParsing(lines, field, owner, raw, value, indent, field.name);
  }
}

function emitScalarParsing(
  lines: string[], field: FieldDefinition, owner: string, raw: string, value: string, indent: string, errorField: string,
): void {
  const fieldExpression = errorField.includes("${") ? "`" + errorField + "`" : JSON.stringify(errorField);
  const type = field.type.name;
  if (type === "string") {
    lines.push(`${indent}if (typeof ${raw} !== \"string\") return { ok: false, field: ${fieldExpression}, message: \"Expected a string\" };`);
    lines.push(`${indent}const ${value} = ${raw};`);
  } else if (type === "number" || type === "int") {
    lines.push(`${indent}const ${value} = typeof ${raw} === \"number\" ? ${raw} : source === \"text\" && typeof ${raw} === \"string\" ? Number(${raw}) : Number.NaN;`);
    const predicate = type === "int" ? `Number.isSafeInteger(${value})` : `Number.isFinite(${value})`;
    lines.push(`${indent}if (!${predicate}) return { ok: false, field: ${fieldExpression}, message: \"Expected ${type === "int" ? "an integer" : "a number"}\" };`);
  } else if (type === "boolean") {
    lines.push(`${indent}const ${value} = typeof ${raw} === \"boolean\" ? ${raw} : source === \"text\" && ${raw} === \"true\" ? true : source === \"text\" && ${raw} === \"false\" ? false : undefined;`);
    lines.push(`${indent}if (${value} === undefined) return { ok: false, field: ${fieldExpression}, message: \"Expected a boolean\" };`);
  } else if (type === "unknown") {
    lines.push(`${indent}const ${value} = ${raw};`);
  } else {
    lines.push(`${indent}const parsed_${value} = parse${type}(${raw}, source);`);
    lines.push(`${indent}if (!parsed_${value}.ok) return { ok: false, field: ${fieldExpression} + \".\" + parsed_${value}.field, message: parsed_${value}.message };`);
    lines.push(`${indent}const ${value} = parsed_${value}.value;`);
  }

  for (const constraint of field.constraints) {
    const message = `Failed @${constraint.name}(${String(constraint.value)})`;
    if (constraint.name === "min") lines.push(`${indent}if (${value} < ${constraint.value}) return { ok: false, field: ${fieldExpression}, message: ${JSON.stringify(message)} };`);
    if (constraint.name === "max") lines.push(`${indent}if (${value} > ${constraint.value}) return { ok: false, field: ${fieldExpression}, message: ${JSON.stringify(message)} };`);
    if (constraint.name === "minLength") lines.push(`${indent}if (${value}.length < ${constraint.value}) return { ok: false, field: ${fieldExpression}, message: ${JSON.stringify(message)} };`);
    if (constraint.name === "maxLength") lines.push(`${indent}if (${value}.length > ${constraint.value}) return { ok: false, field: ${fieldExpression}, message: ${JSON.stringify(message)} };`);
    if (constraint.name === "pattern") lines.push(`${indent}if (!pattern_${owner}_${field.name}.test(${value})) return { ok: false, field: ${fieldExpression}, message: ${JSON.stringify(message)} };`);
  }
}

function emitServer(lines: string[], app: AppDefinition): void {
  lines.push(`export const server = Bun.serve({`);
  lines.push("  port: Number(Bun.env.PORT ?? 3000),");
  lines.push("  async fetch(request): Promise<Response> {");
  lines.push("    const url = new URL(request.url);");
  lines.push(`    const basePath: string = ${JSON.stringify(app.basePath)};`);
  lines.push("    if (basePath && !url.pathname.startsWith(basePath + \"/\") && url.pathname !== basePath) return json({ error: \"NOT_FOUND\" }, 404);");
  lines.push("    const pathname = basePath ? url.pathname.slice(basePath.length) || \"/\" : url.pathname;");
  lines.push("    const segments = pathname.split(\"/\").filter(Boolean);");
  lines.push("    switch (request.method) {");

  const methods = [...new Set(app.routes.map((route) => route.method))];
  for (const method of methods) {
    lines.push(`      case ${JSON.stringify(method)}: {`);
    for (const route of app.routes.filter((item) => item.method === method)) emitRoute(lines, route, app);
    lines.push("        break;", "      }");
  }
  lines.push("    }");
  lines.push("    return json({ error: \"NOT_FOUND\" }, 404);");
  lines.push("  },", "});", "");
  lines.push(`console.log(${JSON.stringify(app.name + " listening")}, server.url.href);`);
}

function emitRoute(lines: string[], route: RouteDefinition, app: AppDefinition): void {
  const parts = route.path.split("/").filter(Boolean);
  const checks = [`segments.length === ${parts.length}`];
  const paramsEntries: string[] = [];
  parts.forEach((part, index) => {
    if (part.startsWith(":")) paramsEntries.push(`${JSON.stringify(part.slice(1))}: decodePathSegment(segments[${index}])`);
    else checks.push(`segments[${index}] === ${JSON.stringify(part)}`);
  });
  lines.push(`        if (${checks.join(" && ")}) {`);
  if (route.permission) {
    lines.push(`          if (!(await appHandlers.authorize(request, Permission.${route.permission}))) return json({ error: \"FORBIDDEN\" }, 403);`);
  }
  if (route.params) {
    lines.push(`          const parsedParams = parse${route.params}({ ${paramsEntries.join(", ")} }, \"text\");`);
    lines.push("          if (!parsedParams.ok) return invalid(parsedParams);");
  }
  if (route.query) {
    const queryType = app.types.find((type) => type.name === route.query)!;
    lines.push("          const rawQuery: Record<string, unknown> = {};");
    for (const field of queryType.fields) {
      if (field.type.array) {
        lines.push(`          if (url.searchParams.has(${JSON.stringify(field.name)})) rawQuery[${JSON.stringify(field.name)}] = url.searchParams.getAll(${JSON.stringify(field.name)});`);
      } else {
        lines.push(`          if (url.searchParams.has(${JSON.stringify(field.name)})) rawQuery[${JSON.stringify(field.name)}] = url.searchParams.get(${JSON.stringify(field.name)});`);
      }
    }
    lines.push(`          const parsedQuery = parse${route.query}(rawQuery, \"text\");`);
    lines.push("          if (!parsedQuery.ok) return invalid(parsedQuery);");
  }
  if (route.body) {
    lines.push(`          const parsedBody = parse${route.body}(await bodyAsJson(request));`);
    lines.push("          if (!parsedBody.ok) return invalid(parsedBody);");
  }
  if (route.invocation && app.nest) {
    const variables = new Map([...app.nest.providers, ...app.nest.controllers].map((item) => [item.name, item.variable]));
    const controller = variables.get(route.invocation.controller)!;
    for (const guardName of route.invocation.guards) {
      const guard = variables.get(guardName);
      if (!guard) throw new Error(`Guard '${guardName}' has no generated provider instance`);
      lines.push(`          if (!(await ${guard}.canActivate(executionContext(request, ${controller}, ${controller}.${route.invocation.method})))) return json({ error: \"FORBIDDEN\" }, 403);`);
    }
  }
  const params = route.params ? "parsedParams.value" : "undefined";
  const query = route.query ? "parsedQuery.value" : "undefined";
  const body = route.body ? "parsedBody.value" : "undefined";
  if (route.invocation && app.nest) {
    const controller = app.nest.controllers.find((item) => item.name === route.invocation!.controller)!.variable;
    const args = route.invocation.arguments.map((argument) => {
      if (argument.kind === "request") return "request";
      if (argument.kind === "body") return body;
      if (argument.kind === "params") return params;
      if (argument.kind === "query") return query;
      if (argument.kind === "param") return `${params}[${JSON.stringify(argument.name)}]`;
      return `${query}[${JSON.stringify(argument.name)}]`;
    });
    lines.push("          try {");
    lines.push(`            const result = await ${controller}.${route.invocation.method}(${args.join(", ")});`);
    lines.push(`            return toResponse(result, ${route.status ?? 200});`);
    lines.push("          } catch (error) { return exceptionResponse(error); }");
  } else {
    lines.push(`          const result = await appHandlers.${route.handler}({ request, params: ${params}, query: ${query}, body: ${body} });`);
    lines.push(`          return toResponse(result, ${route.status ?? 200});`);
  }
  lines.push("        }");
}

function tsType(type: TypeRef): string {
  const scalar = type.name === "int" ? "number" : type.name;
  return type.array ? `${scalar}[]` : scalar;
}
